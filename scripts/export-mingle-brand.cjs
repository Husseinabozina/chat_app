#!/usr/bin/env node
// Export the editable SVG master; no image generation or app startup side effect.
// Requires sharp 0.35.4 in this environment (or supplied through NODE_PATH).
const fs = require("node:fs/promises");
const path = require("node:path");
const sharp = require("sharp");
const root = path.resolve(__dirname, "..");
const mobile = path.join(root, "apps/mobile");
const color = process.argv[2];
const background = process.argv[3] ?? "#FFF8F5";
if (
  ![color, background]
    .filter((c) => c !== undefined)
    .every((c) => /^#[\da-f]{6}$/i.test(c))
) {
  throw new Error("Use two #RRGGBB colors: mark and launcher background.");
}
async function writePng(svg, size, output, flatten = false) {
  let render = sharp(Buffer.from(svg), { density: 144 }).resize(size, size);
  if (flatten) render = render.flatten({ background });
  await fs.mkdir(path.dirname(output), { recursive: true });
  await render.png().toFile(output);
}
async function main() {
  const master = await fs.readFile(
    path.join(mobile, "assets/brand/mingle-mark.svg"),
    "utf8",
  );
  const viewBox = master.match(/viewBox="0 0 (\d+) (\d+)"/);
  if (!viewBox || viewBox[1] !== viewBox[2]) {
    throw new Error("Expected a square SVG viewBox starting at 0 0.");
  }
  const viewBoxSize = Number(viewBox[1]);
  let mark = master;
  if (color) {
    const mix = (other, fraction) => {
      const channels = [1, 3, 5].map((position) => {
        const a = parseInt(color.slice(position, position + 2), 16);
        const b = parseInt(other.slice(position, position + 2), 16);
        return Math.round(a + (b - a) * fraction)
          .toString(16)
          .padStart(2, "0");
      });
      return `#${channels.join("")}`;
    };
    const replacements = {
      "primary-start": mix("#FFFFFF", 0.02),
      "primary-end": mix("#000000", 0.015),
      "highlight-start": mix("#FFFFFF", 0.8),
      "highlight-end": mix("#FFFFFF", 0.82),
      "fold-start": mix("#FFFFFF", 0.65),
      "fold-end": mix("#FFFFFF", 0.6),
    };
    for (const [id, replacement] of Object.entries(replacements)) {
      const stop = new RegExp(`(id="${id}"[^>]*stop-color=")[^"]+(")`);
      if (!stop.test(mark)) throw new Error(`Missing gradient stop: ${id}`);
      mark = mark.replace(stop, `$1${replacement}$2`);
    }
  }
  // Keep the app's native vector geometry in sync with the SVG master.
  const dartPaths = [
    "// Generated by scripts/export-mingle-brand.cjs from the SVG master.",
    "// Re-export after editing geometry; colors belong to MingleBrandPalette.",
    "import 'dart:ui';",
    "",
    "abstract final class MingleLogoPaths {",
    `  static const viewBoxSize = ${viewBoxSize}.0;`,
  ];
  const layers = [...master.matchAll(/<path id="([^"]+)"[^>]*d="([^"]+)"/g)];
  if (
    layers.map((layer) => layer[1]).join(",") !== "bubble,plane,highlight,fold"
  ) {
    throw new Error(
      "Expected bubble, plane, highlight and fold SVG layers in order.",
    );
  }
  for (const [, name, data] of layers) {
    dartPaths.push(`  static final ${name} = Path()`);
    const tokens = data.match(/[a-zA-Z]|-?\d+(?:\.\d+)?/g);
    let position = 0;
    while (position < tokens.length) {
      const command = tokens[position++];
      if (command === "M")
        dartPaths.push(
          `    ..moveTo(${tokens[position++]}, ${tokens[position++]})`,
        );
      else if (command === "Q")
        dartPaths.push(
          `    ..quadraticBezierTo(${tokens[position++]}, ${tokens[position++]}, ${tokens[position++]}, ${tokens[position++]})`,
        );
      else if (command === "Z") dartPaths.push("    ..close();");
      else throw new Error(`Unsupported SVG path command: ${command}`);
    }
  }
  dartPaths.push("}", "");
  await fs.writeFile(
    path.join(mobile, "lib/core/presentation/mingle_logo_paths.dart"),
    dartPaths.join("\n"),
  );
  await writePng(mark, 768, path.join(mobile, "assets/art/mingle-mark.png"));
  const inner = mark.replace(/<svg[^>]*>/, "").replace("</svg>", "");
  const launcher = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128"><rect width="128" height="128" fill="${background}"/><g transform="translate(8 8) scale(${112 / viewBoxSize})">${inner}</g></svg>`;
  const ios = path.join(mobile, "ios/Runner/Assets.xcassets");
  const icons = JSON.parse(
    await fs.readFile(
      path.join(ios, "AppIcon.appiconset/Contents.json"),
      "utf8",
    ),
  );
  for (const item of icons.images) {
    if (!item.filename) continue;
    const pixels = Math.round(parseFloat(item.size) * parseFloat(item.scale));
    await writePng(
      launcher,
      pixels,
      path.join(ios, "AppIcon.appiconset", item.filename),
      true,
    );
  }
  for (const [density, size] of [
    ["mdpi", 48],
    ["hdpi", 72],
    ["xhdpi", 96],
    ["xxhdpi", 144],
    ["xxxhdpi", 192],
  ]) {
    await writePng(
      launcher,
      size,
      path.join(
        mobile,
        `android/app/src/main/res/mipmap-${density}/ic_launcher.png`,
      ),
      true,
    );
    await writePng(
      mark,
      size * 2,
      path.join(
        mobile,
        `android/app/src/main/res/drawable-${density}/mingle_mark.png`,
      ),
    );
  }
  for (const [suffix, scale] of [
    ["", 1],
    ["@2x", 2],
    ["@3x", 3],
  ]) {
    await writePng(
      mark,
      112 * scale,
      path.join(ios, `LaunchImage.imageset/LaunchImage${suffix}.png`),
    );
  }
  console.log(
    "Exported transparent app mark, opaque launcher icons and native splash marks.",
  );
}
main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
